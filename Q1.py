"""
Take two numbers as input from the user. Print their sum, difference,
product, and remainder
"""

a = int(input("Enter the First Number: "))
b = int(input("Enter the Second Number: "))
print(f"Sum of two Numbers is {a+b}")
print(f"Difference of Two Number is {a-b}")
print(f"Product of Two number is {a*b}")
print(f"Remainder of Two Number is {a%b}")
